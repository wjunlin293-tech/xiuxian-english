  function adaptPage(page) {
    ["heading", "cont", "body", "lead", "prompt"].forEach(function (key) {
      if (typeof page[key] === "string") {
        const raw = page[key];
        page[key] = function () { return heroText(raw); };
      } else if (typeof page[key] === "function") {
        const rawFn = page[key];
        page[key] = function () { return heroText(rawFn()); };
      }
    });
    if (Array.isArray(page.options)) {
      page.options.forEach(function (opt) {
        if (typeof opt.label === "string") {
          const raw = opt.label;
          opt.label = function () { return heroText(raw); };
        }
      });
    }
    return page;
  }

